"""Build the phone controller runtime: src/rc/ -> out/web/rc/rc.js and out/web/rc/dev.html.

rc.js = every part (src/rc/parts/*.js), the CSS, the export template, the presets and exporter.js,
wrapped in one function that sets window.RC = {exportHTML, preset, presets, ...} (the builder page
from Task 4 and the tests use it). dev.html renders a controller from ?p=<preset>&lang=<th|en|lo>
?c=<config JSON> or ?saved=1 (the builder's saved config); without parameters it lists the presets.

Checks before writing: every //@ /*@ <!--@ comment has th (Thai), en (plain English) and lo (Lao
script); parts, CSS and template have no other comments, so an exported file never mixes languages.
After writing, node renders every preset in every language and checks nothing is left unfilled.
"""
import json, os, re, subprocess, sys

ROOT = '/home/claude/site'
SRC, OUT = ROOT + '/src/rc', ROOT + '/out/web/rc'
PARTS = ['core', 'link_ble', 'link_mqtt', 'mode_buttons', 'mode_stick', 'extra_buttons', 'terminal']
PRESET_KEYS = ['hello', 'tap4', 'hold4', 'stick1', 'stick2arm', 'mqtt-hello', 'mqtt-drive']
THAI, LAO = re.compile('[฀-๿]'), re.compile('[຀-໿]')
NOTE = re.compile(r'(//|/\*|<!--)@ th=([^|\n]*)\|en=([^|\n]*)\|lo=(.*?)( \*/| -->)?$', re.M)
OTHER_COMMENT = re.compile(r'(?<![:\w])//|/\*(?!==)|<!--(?!==)')
problems = []


def read(name):
    return open(os.path.join(SRC, name), encoding='utf-8').read()


def check_comments(name, src):
    for m in NOTE.finditer(src):
        th, en, lo = (g.strip() for g in m.group(2, 3, 4))
        at = f'{name}:{src.count(chr(10), 0, m.start()) + 1}'
        if not THAI.search(th) or LAO.search(th): problems.append(f'{at}: th must be Thai')
        if not LAO.search(lo) or THAI.search(lo): problems.append(f'{at}: lo must be Lao script')
        if not en or THAI.search(en) or LAO.search(en): problems.append(f'{at}: en must be plain English')
    for i, line in enumerate(NOTE.sub('', src).splitlines(), 1):
        if '@ th=' in line or OTHER_COMMENT.search(line):
            problems.append(f'{name}:{i}: comment without th/en/lo: {line.strip()[:70]}')


def js_string(s):
    """JSON string usable inside JS, also safe if rc.js is ever inlined in a <script> tag."""
    return json.dumps(s, ensure_ascii=False).replace('</', '<\\/')


parts = {p: read(f'parts/{p}.js') for p in PARTS}
css, template, exporter = read('parts/style.css'), read('export_template.html'), read('exporter.js')
presets = json.loads(read('presets.json'))
for p, src in parts.items(): check_comments(f'parts/{p}.js', src)
check_comments('parts/style.css', css)
check_comments('export_template.html', template)
for note in re.findall(r"say\('(//@ th=[^']*)'\)", exporter): check_comments('exporter.js', note)  # CONFIG comments
if sorted(presets) != sorted(PRESET_KEYS): problems.append(f'presets.json keys {sorted(presets)} != {sorted(PRESET_KEYS)}')
if problems:
    print('RC PROBLEMS:\n  ' + '\n  '.join(problems)); sys.exit(1)

rc_js = '\n'.join([
    '/* MATRIX Mini R4 phone controller runtime. Generated by src/build_rc.py from src/rc/ (edit those files). */',
    '(function () {',
    "'use strict';",
    'const PARTS = {\n' + ',\n'.join(f'  {json.dumps(k)}: {js_string(v)}' for k, v in parts.items()) + '\n};',
    'const CSS = ' + js_string(css) + ';',
    'const TEMPLATE = ' + js_string(template) + ';',
    'const PRESETS = ' + json.dumps(presets, ensure_ascii=False).replace('</', '<\\/') + ';',
    exporter.strip(),
    'window.RC = { exportHTML, preset, presets: PRESETS, BROKER };',
    '})();',
    '',
])

DEV = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<link rel="icon" href="data:,">
<title>Controller dev page</title>
<script src="rc.js"></script>
</head>
<body style="font: 16px system-ui, sans-serif; padding: 16px">
<script>
(function () {
  const q = new URLSearchParams(location.search), lang = q.get('lang') || 'th';
  let cfg = q.get('c') ? JSON.parse(q.get('c')) : RC.preset(q.get('p'));
  if (q.get('saved')) { try { cfg = JSON.parse(localStorage.getItem('mbr4-rc')); } catch (e) {} }  // the builder's current config
  if (cfg) {
    const html = RC.exportHTML(cfg, lang);
    addEventListener('load', () => { document.open(); document.write(html); document.close(); });
    return;
  }
  const rows = Object.keys(RC.presets).map((k) => '<li>' + ['th', 'en', 'lo']
    .map((l) => '<a href="?p=' + k + '&lang=' + l + '">' + k + ' ' + l + '</a>').join(' · ') + '</li>');
  document.body.innerHTML = '<h1>Controller dev page</h1><p>?p=&lt;preset&gt;&amp;lang=th|en|lo or ?c=&lt;config JSON&gt; or ?saved=1</p><ul>' + rows.join('') + '</ul>';
})();
</script>
</body>
</html>
"""

os.makedirs(OUT, exist_ok=True)
open(OUT + '/rc.js', 'w', encoding='utf-8').write(rc_js)
open(OUT + '/dev.html', 'w', encoding='utf-8').write(DEV)
# the builder page (rc/index.html): UI in builder.html, texts in i18n.js
open(OUT + '/index.html', 'w', encoding='utf-8').write(read('builder.html'))
open(OUT + '/i18n.js', 'w', encoding='utf-8').write(read('i18n.js'))

SMOKE = r"""
const vm = require('vm'), fs = require('fs'), ctx = vm.createContext({ window: {} });
vm.runInContext(fs.readFileSync(process.argv[1], 'utf8'), ctx);
const RC = ctx.window.RC, bad = [], lines = {};
for (const k of Object.keys(RC.presets)) for (const l of ['th', 'en', 'lo']) {
  const h = RC.exportHTML(RC.preset(k), l);
  if (/\{\{|\[\[|@ th=/.test(h)) bad.push(k + ' ' + l + ': unfilled {{ [[ or //@');
  if (l !== 'th' && /[฀-๿]/.test(h)) bad.push(k + ' ' + l + ': Thai letters');
  if (l !== 'lo' && /[຀-໿]/.test(h)) bad.push(k + ' ' + l + ': Lao letters');
  if (l === 'th') lines[k] = h.replace(/\n$/, '').split('\n').length;
}
console.log(JSON.stringify({ bad, lines }));
"""
try:
    res = subprocess.run(['node', '-e', SMOKE, OUT + '/rc.js'], capture_output=True, text=True, timeout=60)
except FileNotFoundError:
    print('rc: node not found, skipped export smoke check'); res = None
if res is not None:
    if res.returncode: print('RC SMOKE FAILED\n' + res.stderr); sys.exit(1)
    out = json.loads(res.stdout)
    if out['bad']: print('RC PROBLEMS:\n  ' + '\n  '.join(out['bad'])); sys.exit(1)
    print('rc: wrote out/web/rc/rc.js (%d KB) and dev.html; exported lines (th): %s'
          % (len(rc_js.encode()) // 1024, ', '.join(f'{k} {n}' for k, n in out['lines'].items())))
